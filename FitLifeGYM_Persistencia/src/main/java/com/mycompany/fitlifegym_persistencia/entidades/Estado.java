
package com.mycompany.fitlifegym_persistencia.entidades;

/**
 * Enumeración que representa
 * el estado de una entidad
 * dentro del sistema.
 * 
 * Define si un registro
 * se encuentra activo
 * o inactivo.
 * 
 * @author Luis
 */
public enum Estado {
    /**
     * Indica que la entidad
     * se encuentra activa.
     */
    ACTIVO,
    
    /**
     * Indica que la entidad
     * se encuentra inactiva.
     */
    INACTIVO
}
