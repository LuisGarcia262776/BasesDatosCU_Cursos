    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // ── Validaciones ──────────────────────────────────────────────────
        if (txtHoraInicio.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "La hora de inicio es obligatoria.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (txtHoraFin.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "La hora de fin es obligatoria.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (txtCupoMaximo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El cupo máximo es obligatorio.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (cmbDias.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Selecciona un dia.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // Construir el DTO 
            String amPm = cmbAm_Pm.getSelectedItem().toString();

            LocalTime horaInicio = parsearHora(txtHoraInicio.getText().trim(), amPm);
            LocalTime horaFin = parsearHora(txtHoraFin.getText().trim(), amPm);

            if (horaInicio.isAfter(horaFin)) {
                JOptionPane.showMessageDialog(this, "La hora de inicio no puede ser después de la hora fin.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            List<HorarioDiaSemanaDTO> dias = new ArrayList<>();
            dias.add(HorarioDiaSemanaDTO.valueOf(cmbDias.getSelectedItem().toString()));

            HorarioDTO horarioDTO = new HorarioDTO(curso.getIdCurso(), dias, horaInicio, horaFin, Integer.parseInt(txtCupoMaximo.getText().trim()), 0);

            ConfirmacionHorarioFORM confirmacion = new ConfirmacionHorarioFORM(control, horarioDTO);
            confirmacion.setVisible(true);
            this.dispose(); // 

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El cupo máximo debe ser un número entero.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Formato de hora inválido. Usa HH:mm (ej. 9:00)", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

