    // Convierte 9:00 + AM/PM a LocalTime 
    private LocalTime parsearHora(String hora, String amPm) {
        // Acepta "9:00" o "09:00"
        String[] partes = hora.split(":");
        int horas   = Integer.parseInt(partes[0].trim());
        int minutos = partes.length > 1 ? Integer.parseInt(partes[1].trim()) : 0;

        if (amPm.equals("PM") && horas != 12){
            horas += 12;
        }
        if (amPm.equals("AM") && horas == 12){
            horas  = 0;
        }

        return LocalTime.of(horas, minutos);
    }
   

